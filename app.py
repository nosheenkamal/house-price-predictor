import streamlit as st
import pandas as pd
import joblib

# Load trained model
model = joblib.load("house_price_model.pkl")

# Page configuration
st.set_page_config(
    page_title="House Price Predictor",
    page_icon="🏠",
    layout="wide"
)

# Custom styling
st.markdown("""
<style>
.main {
    padding-top: 2rem;
}

.title {
    text-align: center;
    font-size: 42px;
    font-weight: bold;
}

.subtitle {
    text-align: center;
    font-size: 18px;
    margin-bottom: 30px;
}

.result-box {
    padding: 25px;
    border-radius: 15px;
    text-align: center;
    margin-top: 20px;
}
</style>
""", unsafe_allow_html=True)

# Header
st.markdown(
    '<div class="title">🏠 House Price Predictor</div>',
    unsafe_allow_html=True
)

st.markdown(
    '<div class="subtitle">Predict an estimated house price using machine learning</div>',
    unsafe_allow_html=True
)

st.divider()

# Input sections
st.subheader("🏡 Property Details")

col1, col2 = st.columns(2)

with col1:
    bedrooms = st.number_input(
        "Bedrooms",
        min_value=0.0,
        max_value=10.0,
        value=3.0,
        step=1.0
    )

    bathrooms = st.number_input(
        "Bathrooms",
        min_value=0.0,
        max_value=10.0,
        value=2.0,
        step=0.25
    )

    sqft_living = st.number_input(
        "Living Area (sqft)",
        min_value=100,
        max_value=20000,
        value=2000,
        step=100
    )

    sqft_lot = st.number_input(
        "Lot Size (sqft)",
        min_value=100,
        max_value=2000000,
        value=8000,
        step=500
    )

    floors = st.number_input(
        "Floors",
        min_value=1.0,
        max_value=4.0,
        value=1.5,
        step=0.5
    )

    waterfront = st.selectbox(
        "Waterfront",
        options=[0, 1],
        format_func=lambda x: "Yes" if x == 1 else "No"
    )

    view = st.slider(
        "View Rating",
        min_value=0,
        max_value=4,
        value=0
    )

with col2:
    condition = st.slider(
        "House Condition",
        min_value=1,
        max_value=5,
        value=3
    )

    sqft_above = st.number_input(
        "Above Ground Area (sqft)",
        min_value=100,
        max_value=15000,
        value=1800,
        step=100
    )

    sqft_basement = st.number_input(
        "Basement Area (sqft)",
        min_value=0,
        max_value=6000,
        value=0,
        step=100
    )

    yr_built = st.number_input(
        "Year Built",
        min_value=1800,
        max_value=2026,
        value=1975,
        step=1
    )

    yr_renovated = st.number_input(
        "Year Renovated",
        min_value=0,
        max_value=2026,
        value=0,
        step=1
    )

    city = st.text_input(
        "City",
        value="Seattle"
    )

    statezip = st.text_input(
        "State ZIP",
        value="WA 98101"
    )

st.divider()

# Prediction button
if st.button("💰 Predict House Price", use_container_width=True):

    input_data = pd.DataFrame({
        "bedrooms": [bedrooms],
        "bathrooms": [bathrooms],
        "sqft_living": [sqft_living],
        "sqft_lot": [sqft_lot],
        "floors": [floors],
        "waterfront": [waterfront],
        "view": [view],
        "condition": [condition],
        "sqft_above": [sqft_above],
        "sqft_basement": [sqft_basement],
        "yr_built": [yr_built],
        "yr_renovated": [yr_renovated],
        "city": [city],
        "statezip": [statezip]
    })

    prediction = model.predict(input_data)[0]

    st.success(
        f"### 🏠 Estimated House Price: ${prediction:,.2f}"
    )

    st.info(
        "This is an estimated price generated by the trained Multiple Linear Regression model."
    )

st.divider()

st.caption(
    "House Price Predictor | Machine Learning Project | Multiple Linear Regression"
)